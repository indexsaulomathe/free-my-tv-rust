//! `web/zones.js`: each time zone's main city, country and position, from the tz database (`tools/make_zones.py`).

use crate::json::{dumps, Style};
use serde_json::{Map, Value};
use std::collections::BTreeMap;

/// Names the zone id can't spell (accents, or a city other than the one in the id).
pub const NAMES: [(&str, &str); 18] = [
    ("America/Sao_Paulo", "São Paulo"),
    ("America/Belem", "Belém"),
    ("America/Maceio", "Maceió"),
    ("America/Araguaina", "Araguaína"),
    ("America/Cuiaba", "Cuiabá"),
    ("America/Santarem", "Santarém"),
    ("America/Eirunepe", "Eirunepé"),
    ("America/Bahia", "Salvador"),
    ("America/Noronha", "Fernando de Noronha"),
    ("America/Bogota", "Bogotá"),
    ("America/Asuncion", "Asunción"),
    ("America/Merida", "Mérida"),
    ("America/Mazatlan", "Mazatlán"),
    ("America/Cancun", "Cancún"),
    ("America/Ciudad_Juarez", "Ciudad Juárez"),
    ("America/Argentina/Cordoba", "Córdoba"),
    ("America/Argentina/Tucuman", "Tucumán"),
    ("Asia/Ho_Chi_Minh", "Ho Chi Minh City"),
];

/// "+4230" or "-0740023" (±DDMM[SS] or ±DDDMM[SS]) → decimal degrees rounded to 2 places.
pub fn degrees(text: &str, width: usize) -> Option<f64> {
    let sign = if text.starts_with('-') { -1.0 } else { 1.0 };
    let digits = text.get(1..)?;
    let part = |a: usize, b: usize| -> Option<f64> {
        match digits.get(a..b.min(digits.len())) {
            Some("") | None => Some(0.0),
            Some(s) => s.parse::<f64>().ok(),
        }
    };
    let (d, m, s) = (
        part(0, width)?,
        part(width, width + 2)?,
        part(width + 2, width + 4)?,
    );
    let value = sign * (d + m / 60.0 + s / 3600.0);
    format!("{value:.2}").parse().ok()
}

/// Python's `'%g' % x` for a number with at most 2 decimals.
pub fn g(x: f64) -> String {
    let s = format!("{x:.2}");
    let s = s.trim_end_matches('0').trim_end_matches('.');
    if s == "-0" {
        "-0".into()
    } else {
        s.into()
    }
}

/// The `ZONES` map from `zone.tab` and the links in `tzdata.zi`.
pub fn zones(zone_tab: &str, tzdata_zi: &str) -> BTreeMap<String, String> {
    let names: BTreeMap<&str, &str> = NAMES.iter().copied().collect();
    let mut zones = BTreeMap::new();
    for line in zone_tab.lines() {
        if line.starts_with('#') || line.trim().is_empty() {
            continue;
        }
        let cols: Vec<&str> = line.split('\t').collect();
        if cols.len() < 3 {
            continue;
        }
        let (country, coords, zone) = (cols[0], cols[1], cols[2]);
        let split = coords[1..]
            .find(['+', '-'])
            .map(|p| p + 1)
            .unwrap_or(coords.len());
        let (Some(lat), Some(lon)) = (degrees(&coords[..split], 2), degrees(&coords[split..], 3))
        else {
            continue;
        };
        let mut value = format!("{country},{},{}", g(lat), g(lon));
        let derived = zone.rsplit('/').next().unwrap_or(zone).replace('_', " ");
        if let Some(name) = names.get(zone) {
            if *name != derived {
                value.push(',');
                value.push_str(name);
            }
        }
        zones.insert(zone.to_string(), value);
    }
    for line in tzdata_zi.lines() {
        let parts: Vec<&str> = line.split_whitespace().collect();
        if parts.len() == 3
            && parts[0] == "L"
            && zones.contains_key(parts[1])
            && !zones.contains_key(parts[2])
        {
            zones.insert(parts[2].to_string(), format!("={}", parts[1]));
        }
    }
    zones
}

/// The text of `web/zones.js`.
pub fn zones_js(zones: &BTreeMap<String, String>) -> String {
    let map: Map<String, Value> = zones
        .iter()
        .map(|(k, v)| (k.clone(), Value::from(v.as_str())))
        .collect();
    format!(
        "/* Generated by tools/make_zones.py from the tz database (public domain).\n * Time zone → \"country,latitude,longitude[,city]\", or \"=\" + the zone it's another name for. */\nvar ZONES = {};\n",
        dumps(&Value::Object(map), Style::UNICODE_COMPACT)
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn degrees_like_python() {
        assert_eq!(degrees("+4230", 2), Some(42.5));
        assert_eq!(degrees("-2332", 2), Some(-23.53));
        assert_eq!(degrees("-0740023", 3), Some(-74.01));
        assert_eq!(degrees("+1393357", 3), Some(139.57));
        assert_eq!(g(42.5), "42.5");
        assert_eq!(g(0.0), "0");
        assert_eq!(g(-176.66), "-176.66");
        assert_eq!(g(16.0), "16");
    }

    #[test]
    fn small_database() {
        let z = zones("# c\n\nBR\t-2332-04637\tAmerica/Sao_Paulo\tx\nUS\t+404251-0740023\tAmerica/New_York\n",
                      "L America/Sao_Paulo Brazil/East\nL America/New_York America/New_York\nL Nowhere/Z Alias/X\n");
        assert_eq!(
            z.get("America/Sao_Paulo").unwrap(),
            "BR,-23.53,-46.62,São Paulo"
        );
        assert_eq!(z.get("America/New_York").unwrap(), "US,40.71,-74.01");
        assert_eq!(z.get("Brazil/East").unwrap(), "=America/Sao_Paulo");
        assert_eq!(z.len(), 3);
    }
}
