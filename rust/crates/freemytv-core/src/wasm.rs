//! Packs the logic's WebAssembly into `web/logic_wasm.js` (`freemytv make-logic`): without its custom sections
//! (names, producers), in base64, so the TV loads it with the other scripts, from file:// too.

use crate::Error;

fn leb128(data: &[u8], mut i: usize) -> Option<(u64, usize)> {
    let (mut v, mut shift) = (0u64, 0);
    loop {
        let b = *data.get(i)?;
        i += 1;
        v |= u64::from(b & 0x7f) << shift;
        if b < 0x80 {
            return Some((v, i));
        }
        shift += 7;
        if shift > 63 {
            return None;
        }
    }
}

/// The module without its custom sections (id 0): they only help debuggers.
pub fn strip(wasm: &[u8]) -> Result<Vec<u8>, Error> {
    let bad = || Error("not a WebAssembly module".into());
    if wasm.len() < 8 || &wasm[..4] != b"\0asm" {
        return Err(bad());
    }
    let mut out = wasm[..8].to_vec();
    let mut i = 8;
    while i < wasm.len() {
        let id = wasm[i];
        let (len, body) = leb128(wasm, i + 1).ok_or_else(bad)?;
        let end = body
            .checked_add(len as usize)
            .filter(|&e| e <= wasm.len())
            .ok_or_else(bad)?;
        if id != 0 {
            out.extend_from_slice(&wasm[i..end]);
        }
        i = end;
    }
    Ok(out)
}

pub fn base64(data: &[u8]) -> String {
    const A: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    let mut out = String::with_capacity(data.len().div_ceil(3) * 4);
    for c in data.chunks(3) {
        let n = (u32::from(c[0]) << 16)
            | (u32::from(*c.get(1).unwrap_or(&0)) << 8)
            | u32::from(*c.get(2).unwrap_or(&0));
        for k in 0..4 {
            if k <= c.len() {
                out.push(A[(n >> (18 - 6 * k) & 63) as usize] as char);
            } else {
                out.push('=');
            }
        }
    }
    out
}

pub fn logic_js(wasm: &[u8]) -> Result<String, Error> {
    Ok(format!(
        "/* Generated by `freemytv make-logic` from rust/crates/freemytv-logic: the WebAssembly web/logic.js loads. */\n\
         var LOGIC_WASM = '{}';\n",
        base64(&strip(wasm)?)
    ))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn base64_like_python() {
        assert_eq!(base64(b""), "");
        assert_eq!(base64(b"f"), "Zg==");
        assert_eq!(base64(b"fo"), "Zm8=");
        assert_eq!(base64(b"foo"), "Zm9v");
        assert_eq!(base64(b"\xff\xfe\x00x"), "//4AeA==");
    }

    #[test]
    fn strips_custom_sections() {
        // header, a custom section "n" (id 0, 3 bytes), a type section (id 1, 1 byte: zero types)
        let m = [
            b"\0asm\x01\0\0\0".as_slice(),
            &[0, 3, 1, b'n', 9],
            &[1, 1, 0],
        ]
        .concat();
        assert_eq!(
            strip(&m).unwrap(),
            [b"\0asm\x01\0\0\0".as_slice(), &[1, 1, 0]].concat()
        );
        assert!(strip(b"nope").is_err());
        assert!(strip(&[b"\0asm\x01\0\0\0".as_slice(), &[1, 9, 0]].concat()).is_err());
    }
}
