//! The web app's files, as `files()` in `tools/webapp.py` gathers them: `web/`, `config.js`, `coins.js`, `i18n.js`,
//! the app's symbols and its font.

use crate::config::Config;
use crate::json::{dumps, Style};
use crate::{i18n, sorted_names, Error, Repo};
use regex::Regex;
use serde_json::Value;
use std::collections::BTreeMap;
use std::fs;
use std::path::Path;

/// Path inside the app → contents, sorted by path.
pub type Files = BTreeMap<String, Vec<u8>>;

/// The coins' logos (BTC, ETH, SOL, USDT) as lists of SVG paths, from the Android app's vector drawables.
pub fn coins(repo: &Repo) -> Result<Vec<Vec<String>>, Error> {
    let re = Regex::new(r#"android:pathData="([^"]+)""#).unwrap();
    ["btc", "eth", "sol", "usdt"]
        .iter()
        .map(|name| {
            let xml = repo.read_string(&format!("app/res/drawable/coin_{name}.xml"))?;
            Ok(re.captures_iter(&xml).map(|c| c[1].to_string()).collect())
        })
        .collect()
}

/// Every file of the web app, for a build made by `made_by` (written into the generated files' headers).
pub fn files(repo: &Repo, config: &Config, made_by: &str) -> Result<Files, Error> {
    let mut out = Files::new();
    let web = repo.path("web");
    for name in sorted_names(&web)? {
        let path = web.join(&name);
        if !path.is_dir() {
            out.insert(name, fs::read(&path)?);
        }
    }
    let icons = web.join("icons");
    for name in sorted_names(&icons)? {
        out.insert(format!("icons/{name}"), fs::read(icons.join(&name))?);
    }
    out.insert(
        "config.js".into(),
        format!("/* Generated by {made_by}. */\nwindow.CONFIG = {};\n", dumps(&config.to_json(), Style::UNICODE)).into_bytes(),
    );
    let coins: Value = coins(repo)?.into_iter().map(|p| Value::from(p)).collect::<Vec<_>>().into();
    out.insert("coins.js".into(), format!("window.COINS = {};\n", dumps(&coins, Style::DEFAULT)).into_bytes());
    let cats = i18n::catalogues(&repo.path("app/assets/i18n"), &web)?;
    out.insert(
        "i18n.js".into(),
        format!("/* Generated by {made_by} from app/assets/i18n. */\nwindow.I18N_CATALOGUES = {};\n", dumps(&cats, Style::UNICODE_COMPACT))
            .into_bytes(),
    );
    let symbols = repo.path("app/assets/symbols");
    for name in sorted_names(&symbols)? {
        if name.ends_with(".png") || name.starts_with("LICENSE") {
            out.insert(format!("symbols/{name}"), fs::read(symbols.join(&name))?);
        }
    }
    for name in ["InterVariable.ttf", "OFL.txt"] {
        out.insert(format!("fonts/{name}"), repo.read(&format!("app/assets/fonts/{name}"))?);
    }
    Ok(out)
}

/// Leaves the files in `dir` (emptied first), to open index.html in a browser.
pub fn preview(app: &Files, dir: &Path) -> Result<(), Error> {
    if dir.is_dir() {
        fs::remove_dir_all(dir)?;
    }
    for (path, content) in app {
        let target = dir.join(path);
        if let Some(parent) = target.parent() {
            fs::create_dir_all(parent)?;
        }
        fs::write(target, content)?;
    }
    Ok(())
}
