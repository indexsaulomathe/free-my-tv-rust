"""tools/webapp.py: config.properties and the web app's files."""
import json
import re

import pytest

import webapp


def write(tmp_path, text):
    path = tmp_path / 'config.properties'
    path.write_text(text, encoding='utf-8')
    return str(path)


def test_defaults_when_empty(tmp_path):
    c = webapp.read_config(write(tmp_path, ''))
    assert c['tmdbKey'] == ''
    assert c['tmdbRegion'] == 'US'
    assert (c['latitude'], c['longitude']) == ('40.7128', '-74.0060')
    assert c['language'] == 'auto' and c['currency'] == 'USD' and c['temperature'] == 'auto'
    assert c['showCrypto'] is True and c['hideAnimation'] is False and c['hideApps'] == []


def test_reads_values_comments_and_quotes(tmp_path):
    c = webapp.read_config(write(tmp_path, '\n'.join([
        '# a comment', '', 'no equals sign here',
        'tmdb_key = "abc123"', 'tmdb_region=BR', 'latitude=-23.55', 'longitude=-46.63',
        'city=São Paulo', 'currency=BRL', 'temperature=C', 'language=pt',
        'show_crypto=FALSE', 'hide_animation=true', 'hide_apps= netflix , ,prime ',
        'url=http://x/?a=b',
    ])))
    assert c['tmdbKey'] == 'abc123'
    assert c['tmdbRegion'] == 'BR'
    assert (c['latitude'], c['longitude']) == ('-23.55', '-46.63')
    assert c['city'] == 'São Paulo'
    assert c['currency'] == 'BRL' and c['temperature'] == 'C' and c['language'] == 'pt'
    assert c['showCrypto'] is False and c['hideAnimation'] is True
    assert c['hideApps'] == ['netflix', 'prime']


def test_empty_values_fall_back(tmp_path):
    c = webapp.read_config(write(tmp_path, 'tmdb_region=\nlanguage=\ncurrency=\nlatitude=\n'))
    assert c['tmdbRegion'] == 'US' and c['language'] == 'auto' and c['currency'] == 'USD'
    assert c['latitude'] == '40.7128'


@pytest.mark.parametrize('bad', ['abc', '1,5', '--1', '1.', '.5'])
def test_latitude_must_be_a_number(tmp_path, bad):
    with pytest.raises(SystemExit):
        webapp.read_config(write(tmp_path, 'latitude=%s\n' % bad))


def test_missing_file_is_created_from_the_example(tmp_path, root):
    path = tmp_path / 'config.properties'
    webapp.read_config(str(path))
    with open(root + '/config.example.properties', encoding='utf-8') as f:
        assert path.read_text(encoding='utf-8') == f.read()


def test_config_from_args(tmp_path):
    assert webapp.config_from_args(['--generic']) == webapp.GENERIC
    assert webapp.config_from_args(['--generic']) is not webapp.GENERIC   # a copy
    other = write(tmp_path, 'city=Lisbon\n')
    assert webapp.config_from_args(['--config', other])['city'] == 'Lisbon'


def test_coins_are_four_svg_path_lists():
    coins = webapp.coins()
    assert len(coins) == 4
    for paths in coins:
        assert paths and all(re.match(r'^[MmLlHhVvCcSsQqTtAaZz0-9.,\s-]+$', p) for p in paths)


def test_catalogues_only_hold_web_keys():
    import translate
    keys = translate.web_keys()
    cats = webapp.catalogues()
    assert 'pt' in cats and 'en' not in cats   # English is the key itself
    for lang, cat in cats.items():
        assert set(cat) <= keys, lang


def test_files_has_everything_the_page_loads(generic, root):
    app = webapp.files(generic, 'test')
    html = app['index.html'].decode('utf-8')
    for src in re.findall(r'<script src="([^"]+)"', html):
        assert src in app, src
    assert 'home.css' in app
    assert 'fonts/InterVariable.ttf' in app and 'fonts/OFL.txt' in app
    assert any(k.startswith('symbols/') and k.endswith('.png') for k in app)
    assert any(k.startswith('icons/') for k in app)
    config = app['config.js'].decode('utf-8')
    assert config.startswith('/* Generated by test. */\nwindow.CONFIG = ')
    assert json.loads(config.split('window.CONFIG = ', 1)[1].rstrip(';\n')) == generic


def test_preview_writes_the_files(tmp_path, generic):
    app = {'index.html': b'<html>', 'icons/a.svg': b'<svg/>'}
    out = tmp_path / 'out'
    (out / 'stale').mkdir(parents=True)
    webapp.preview(app, str(out))
    assert (out / 'index.html').read_bytes() == b'<html>'
    assert (out / 'icons' / 'a.svg').read_bytes() == b'<svg/>'
    assert not (out / 'stale').exists()
